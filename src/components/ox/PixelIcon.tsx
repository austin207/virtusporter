export type PixelArt = keyof typeof ART;

export default function PixelIcon({
  art,
  className,
  invert = false,
}: {
  art: PixelArt | string;
  className?: string;
  invert?: boolean;
}) {
  const rows = ART[art] ?? ART.ros;
  const cx = 7;
  const cy = 7;
  const cells: { x: number; y: number; acc: boolean; d: number }[] = [];
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === '#' || ch === '+') cells.push({ x, y, acc: ch === '+', d: Math.hypot(x - cx, y - cy) });
    }),
  );
  return (
    <svg
      viewBox="0 0 15 15"
      shapeRendering="crispEdges"
      aria-hidden
      className={cn('px-icon overflow-visible', className)}
    >
      {cells.map((c) => (
        <rect
          key={`${c.x}-${c.y}`}
          x={c.x + 0.08}
          y={c.y + 0.08}
          width={0.84}
          height={0.84}
          className={c.acc ? 'px-acc' : 'px-ink'}
          fill={c.acc ? 'rgb(var(--accent))' : invert ? 'rgb(var(--light))' : 'rgb(var(--ink))'}
          style={{ ['--d' as string]: `${(c.d * 28).toFixed(0)}ms` }}
        />
      ))}
    </svg>
  );
}
